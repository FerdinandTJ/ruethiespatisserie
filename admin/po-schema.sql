CREATE TABLE IF NOT EXISTS po_slots (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(100) NOT NULL,
  opens_at BIGINT NOT NULL,
  closes_at BIGINT NOT NULL,
  pickup_from BIGINT NOT NULL,
  pickup_until BIGINT NOT NULL,
  is_open TINYINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS po_products (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slot_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(100) NOT NULL,
  price INT UNSIGNED NOT NULL,
  menu_uid CHAR(32) NULL,
  image VARCHAR(500) NOT NULL DEFAULT '',
  quota INT UNSIGNED NOT NULL,
  reserved INT UNSIGNED NOT NULL DEFAULT 0,
  active TINYINT NOT NULL DEFAULT 1,
  FOREIGN KEY (slot_id) REFERENCES po_slots(id),
  INDEX (slot_id, active),
  UNIQUE KEY po_slot_menu (slot_id, menu_uid)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS po_orders (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slot_id BIGINT UNSIGNED NOT NULL,
  code VARCHAR(24) NOT NULL UNIQUE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  request_hash CHAR(64) NOT NULL UNIQUE,
  customer_name VARCHAR(80) NOT NULL,
  phone VARCHAR(16) NOT NULL,
  note VARCHAR(500) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'pending',
  total INT UNSIGNED NOT NULL,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  FOREIGN KEY (slot_id) REFERENCES po_slots(id),
  INDEX (status, created_at),
  INDEX (phone, status),
  INDEX (slot_id, status, expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS po_lines (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  order_id BIGINT UNSIGNED NOT NULL,
  product_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(100) NOT NULL,
  price INT UNSIGNED NOT NULL,
  qty INT UNSIGNED NOT NULL,
  FOREIGN KEY (order_id) REFERENCES po_orders(id),
  FOREIGN KEY (product_id) REFERENCES po_products(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS po_history (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  order_id BIGINT UNSIGNED NOT NULL,
  status VARCHAR(16) NOT NULL,
  actor VARCHAR(80) NOT NULL,
  created_at BIGINT NOT NULL,
  FOREIGN KEY (order_id) REFERENCES po_orders(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS po_rate (
  bucket_key CHAR(64) PRIMARY KEY,
  attempts INT UNSIGNED NOT NULL,
  expires_at BIGINT NOT NULL,
  INDEX (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
